    const HTML_LANG = { ja: 'ja', en: 'en', zh: 'zh-CN' };

    let elements = [];

    function init() {
        // 日本語原文をDOMから保存（デフォルト表示は日本語）
        elements = Array.from(document.querySelectorAll('[data-i18n]')).map(function (el) {
            return { el: el, key: el.getAttribute('data-i18n'), ja: el.innerHTML };
        });

        document.querySelectorAll('.lang-btn').forEach(function (btn) {
            btn.addEventListener('click', function () {
                setLang(btn.getAttribute('data-lang'));
            });
        });
    }

    function setLang(lang) {
        elements.forEach(function (item) {
            if (lang === 'ja') {
                item.el.innerHTML = item.ja;
            } else {
                const dict = I18N[lang];
                if (dict && dict[item.key] !== undefined) {
                    item.el.innerHTML = dict[item.key];
                } else {
                    item.el.innerHTML = item.ja; // 訳が無い場合は日本語のまま
                }
            }
        });

        document.documentElement.lang = HTML_LANG[lang] || 'ja';
        document.title = PAGE_TITLE[lang] || PAGE_TITLE.ja;

        document.querySelectorAll('.lang-btn').forEach(function (btn) {
            btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
        });
    }

    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', init);
    } else {
        init();
    }
